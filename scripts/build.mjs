// Bundles src/gas/main.ts into dist/Code.js for Apps Script.
// Apps Script only calls top-level functions, so every export of main.ts gets a small
// top-level wrapper that forwards to the bundled module.
import { build } from "esbuild";
import { copyFile, mkdir, writeFile, readFile } from "node:fs/promises";

const GLOBAL = "OrderIntake";

const result = await build({
  entryPoints: ["src/gas/main.ts"],
  bundle: true,
  format: "iife",
  globalName: GLOBAL,
  target: "es2019",
  charset: "utf8",
  write: false,
  legalComments: "none",
});

// An IIFE bundle has no export list in its metafile, so ask esbuild once more for an ES module.
const probe = await build({ entryPoints: ["src/gas/main.ts"], bundle: true, format: "esm", metafile: true, write: false });
const exportsList = Object.values(probe.metafile.outputs)[0].exports.filter((name) => name !== "default").sort();
if (exportsList.length === 0) throw new Error("No exports found in src/gas/main.ts");

const wrappers = exportsList
  .map((name) => `function ${name}() {\n  return ${GLOBAL}.${name}.apply(this, arguments);\n}`)
  .join("\n\n");

const banner = "// Built by scripts/build.mjs from src/. Do not edit this file by hand.\n";
await mkdir("dist", { recursive: true });
await writeFile("dist/Code.js", `${banner}${result.outputFiles[0].text}\n${wrappers}\n`);
await copyFile("appsscript.json", "dist/appsscript.json");

const size = (await readFile("dist/Code.js")).length;
console.log(`dist/Code.js (${size} bytes) exports: ${exportsList.join(", ")}`);
